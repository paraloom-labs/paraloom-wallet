// Swap-output ownership (paraloom-wallet#208).
//
// A private swap runs against exactly ONE shielded account: it spends that
// account's notes and, on the round-trip leg, deposits the bought token back
// to that account's shielded address. The persisted row, however, recorded
// neither the account nor the cluster, while `reconcileSwapOutputs` and
// `recoverReshields` walk EVERY row and file what they recover under whatever
// account they were handed — the currently active one. A swap stranded under
// account A was therefore credited to account B whenever B was active when
// recovery ran: B's balance counted a note it cannot spend (it does not hold
// the spend key the note's commitment binds) and A stayed short.
//
// These cases stay on the wasm-free storage module (`swapOutputs`) plus the
// fake chrome.storage, so they run in a plain Node environment. The recovery
// passes themselves pull the prover wasm and are covered by code inspection:
// both must read through `listSwapOutputsFor`, pinned here.

import { beforeEach, describe, expect, it } from "vitest"

import {
  dismissSwapOutput,
  listSwapOutputs,
  listSwapOutputsFor,
  saveSwapOutput,
  type SwapOutput
} from "../lib/paraloom/swapOutputs"
import { installFakeChrome } from "./support/chromeStorage"

const ACCOUNT_A = "paraloom1account-a"
const ACCOUNT_B = "paraloom1account-b"
const USDC = "EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v"

function row(partial: Partial<SwapOutput> & { freshAddress: string }): SwapOutput {
  return {
    freshSecretKeyHex: "ab".repeat(32),
    outputMint: USDC,
    outAmount: 0,
    swapSignature: "",
    createdAt: 1,
    ...partial
  }
}

beforeEach(() => {
  installFakeChrome()
})

describe("swap output ownership", () => {
  it("scopes the recovery view to the owning account", async () => {
    await saveSwapOutput(
      row({ freshAddress: "freshA", shieldedAddress: ACCOUNT_A, network: "mainnet-beta" })
    )
    await saveSwapOutput(
      row({ freshAddress: "freshB", shieldedAddress: ACCOUNT_B, network: "mainnet-beta" })
    )

    const forA = await listSwapOutputsFor(ACCOUNT_A)
    expect(forA.map((o) => o.freshAddress)).toEqual(["freshA"])
    expect(forA[0].shieldedAddress).toBe(ACCOUNT_A)
    expect(forA[0].network).toBe("mainnet-beta")

    const forB = await listSwapOutputsFor(ACCOUNT_B)
    expect(forB.map((o) => o.freshAddress)).toEqual(["freshB"])

    // The unscoped list still returns every row (Activity/dismiss plumbing
    // and migrations read it); only the recovery passes scope by account.
    expect((await listSwapOutputs()).length).toBe(2)
  })

  it("adopts rows written before the owner field existed instead of orphaning them", async () => {
    // A pre-fix row: no shieldedAddress, no network. It can only have been
    // created by the account that was active when it was written, so the
    // scoped view of whichever account asks includes it — stranding the
    // funds behind it would be worse than the adoption.
    await saveSwapOutput(row({ freshAddress: "legacy" }))
    expect((await listSwapOutputsFor(ACCOUNT_A)).map((o) => o.freshAddress)).toEqual([
      "legacy"
    ])
    expect((await listSwapOutputsFor(ACCOUNT_B)).map((o) => o.freshAddress)).toEqual([
      "legacy"
    ])
  })

  it("keeps the owner when a later writer re-saves the row without one", async () => {
    await saveSwapOutput(
      row({ freshAddress: "freshA", shieldedAddress: ACCOUNT_A, network: "mainnet-beta" })
    )
    // The landed upsert in privateSwap is a fresh literal; a writer that
    // omits the owner (or spells it undefined) must not strip it off the row.
    await saveSwapOutput(
      row({ freshAddress: "freshA", outAmount: 42, swapSignature: "sig" })
    )
    await saveSwapOutput(
      row({
        freshAddress: "freshA",
        outAmount: 42,
        swapSignature: "sig",
        shieldedAddress: undefined,
        network: undefined
      })
    )
    const [stored] = await listSwapOutputs()
    expect(stored.shieldedAddress).toBe(ACCOUNT_A)
    expect(stored.network).toBe("mainnet-beta")
    expect(stored.swapSignature).toBe("sig")
  })

  it("never moves a row to a different account on rewrite", async () => {
    await saveSwapOutput(
      row({ freshAddress: "freshA", shieldedAddress: ACCOUNT_A, network: "mainnet-beta" })
    )
    // Ownership is fixed at creation: the fresh address was generated by the
    // swap the owning account ran, so no later write may re-file the row.
    await saveSwapOutput(
      row({ freshAddress: "freshA", shieldedAddress: ACCOUNT_B, network: "devnet" })
    )
    const [stored] = await listSwapOutputs()
    expect(stored.shieldedAddress).toBe(ACCOUNT_A)
    expect(stored.network).toBe("mainnet-beta")
    expect((await listSwapOutputsFor(ACCOUNT_B)).length).toBe(0)
  })

  it("dismiss removes only the addressed row, whichever account owns it", async () => {
    await saveSwapOutput(
      row({ freshAddress: "freshA", shieldedAddress: ACCOUNT_A, network: "mainnet-beta" })
    )
    await saveSwapOutput(
      row({ freshAddress: "freshB", shieldedAddress: ACCOUNT_B, network: "mainnet-beta" })
    )
    await dismissSwapOutput("freshA")
    expect((await listSwapOutputs()).map((o) => o.freshAddress)).toEqual(["freshB"])
  })
})
