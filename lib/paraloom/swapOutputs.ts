// Private swap-out outputs. A private swap leaves the bought token at a FRESH,
// unlinkable address whose key the wallet generated. That key never leaves the
// wallet, so it must be persisted here or the token would be unrecoverable.
// Stored in extension-local storage (not synced).

/** Cluster a swap settles on. Private swaps are mainnet-only today (the
 *  reconciler always runs against mainnet — see Home.tsx), but the row has
 *  to carry the cluster it was created under so a reader never has to guess
 *  which connection the row belongs to. */
export type SwapNetwork = "mainnet-beta" | "devnet"

export interface SwapOutput {
  /** The fresh, unlinkable address holding the swapped token. */
  freshAddress: string
  /** Secret key (hex) of the fresh address — needed to move the token later. */
  freshSecretKeyHex: string
  /** Output mint (base58) or "SOL". */
  outputMint: string
  /** Output amount the route reported, in the out mint's base units. */
  outAmount: number
  /** The swap transaction signature. Empty until the swap leg completes; a
   *  non-empty value marks the swap done (used to find resumable strands). */
  swapSignature: string
  /** Whether the user asked to re-shield the bought token (a round trip). Saved
   *  so a resumed/recovered swap honors the original intent. */
  reshield?: boolean
  /** Set once the re-shield note has been persisted (either normally or via the
   *  recovery scan), so recovery does not re-scan a settled reshield each connect. */
  reshieldRecovered?: boolean
  /** The shielded account that ran the swap. Recovery files what it recovers
   *  under the account it is handed, so a row without an owner was credited
   *  to whichever account happened to be active when recovery ran — and that
   *  account cannot spend the note, whose commitment binds the owner's key.
   *  Optional in the type because rows persisted before this field existed
   *  have none; writers that know the account must stamp it (privateSwap
   *  does), and `saveSwapOutput` never lets a later write move or strip it. */
  shieldedAddress?: string
  /** The cluster the swap settles on (see SwapNetwork). Same persistence
   *  rules as `shieldedAddress`. */
  network?: SwapNetwork
  createdAt: number
}

const KEY = "paraloom_swap_outputs"

// Upsert by freshAddress: the key is saved early (before the withdraw) so it can
// never be lost, then the same entry is updated with the realized amount +
// signature once the swap lands. Keyed on the address so the two writes collapse
// to one row.
//
// Ownership is fixed at creation. The landed upsert and the recovery passes
// re-send rows they merely read (or fresh literals that never carried the
// owner), so a stored `shieldedAddress`/`network` wins over whatever a later
// write says — omitted, undefined, or even a different account: the fresh
// address was generated by the owning account's swap, and re-filing the row
// under another account is exactly the mis-credit this prevents.
export async function saveSwapOutput(output: SwapOutput): Promise<void> {
  const stored = await chrome.storage.local.get(KEY)
  const current = (stored[KEY] as SwapOutput[]) ?? []
  const i = current.findIndex((o) => o.freshAddress === output.freshAddress)
  if (i >= 0) {
    const merged = { ...current[i], ...output }
    if (current[i].shieldedAddress) merged.shieldedAddress = current[i].shieldedAddress
    if (current[i].network) merged.network = current[i].network
    current[i] = merged
  } else {
    current.push(output)
  }
  await chrome.storage.local.set({ [KEY]: current })
}

export async function listSwapOutputs(): Promise<SwapOutput[]> {
  const stored = await chrome.storage.local.get(KEY)
  return (stored[KEY] as SwapOutput[]) ?? []
}

// Rows that belong to `shieldedAddress`. The recovery passes
// (reconcileSwapOutputs, recoverReshields) must read through this, never
// through listSwapOutputs: they persist recovered notes under the account
// they are given, so acting on another account's row files a note into a
// wallet that does not hold the spend key its commitment binds, while the
// owning account stays short.
//
// Rows with no owner predate the field. They can only have been created by
// the account that was active when they were written, so the scoped view
// adopts them for whichever account asks rather than orphaning the funds
// behind them. Once any write stamps an owner the row is scoped to that
// account for good (see saveSwapOutput).
export async function listSwapOutputsFor(
  shieldedAddress: string
): Promise<SwapOutput[]> {
  const all = await listSwapOutputs()
  return all.filter((o) => !o.shieldedAddress || o.shieldedAddress === shieldedAddress)
}

// Drop a swap row by its fresh address. Used to clear a stale "pending" row the
// reconciler could not positively account for — the funds are already safe (the
// swap either re-shielded into the pool or its input note was never spent), so
// this only removes the misleading Activity entry, never any money.
export async function dismissSwapOutput(freshAddress: string): Promise<void> {
  const stored = await chrome.storage.local.get(KEY)
  const current = (stored[KEY] as SwapOutput[]) ?? []
  const next = current.filter((o) => o.freshAddress !== freshAddress)
  await chrome.storage.local.set({ [KEY]: next })
}
